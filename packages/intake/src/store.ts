export interface IntakeEvent extends Record<string, unknown> {
  at: string;
  type: string;
}

export function appendIntakeEvent(
  workspace: WorkspaceInfo,
  intakeId: string,
  event: IntakeEvent,
): void {
  appendJsonl(intakePath(workspace, intakeId, 'events.jsonl'), event);
}

export interface IntakeEventPage {
  events: IntakeEvent[];
  total: number;
  truncated: boolean;
}

export function readIntakeEvents(
  workspace: WorkspaceInfo,
  intakeId: string,
  options: { limit?: number } = {},
): IntakeEventPage {
  const file = intakePath(workspace, intakeId, 'events.jsonl');
  if (!existsSync(file)) return { events: [], total: 0, truncated: false };
  const lines = readFileSync(file, 'utf8')
    .split('\n')
    .filter((line) => line.trim().length > 0);
  const limit = options.limit ?? 200;
  const slice = lines.slice(-limit);
  const events: IntakeEvent[] = [];
  for (const line of slice) {
    try {
      events.push(JSON.parse(line) as IntakeEvent);
    } catch {
      // Skipped, not fatal: the history exists to explain the run.
    }
  }
  return { events, total: lines.length, truncated: lines.length > slice.length };
}

