export function sourceDir(workspace: WorkspaceInfo, intakeId: string): string {
  return intakePath(workspace, intakeId, 'source');
}

export function sourceFile(
  workspace: WorkspaceInfo,
  intakeId: string,
  contentHash: string,
): string {
  if (!/^[0-9a-f]{64}$/.test(contentHash)) {
    throw new IntakeError('SBI007', 'A source specification digest must be a sha256 hex string.');
  }
  return intakePath(workspace, intakeId, 'source', `${contentHash}.md`);
}

/**
 * Store the submitted specification verbatim, content-addressed.
 *
 * Identical bytes are a no-op: the file already on disk IS the evidence, and
 * rewriting it would change its mtime for no reason. Different bytes land
 * beside it under a different name, so a re-submission never destroys what
 * an earlier approval referenced.
 */
export function storeSourceText(
  workspace: WorkspaceInfo,
  intakeId: string,
  contentHash: string,
  content: string,
): string {
  const file = sourceFile(workspace, intakeId, contentHash);
  if (!existsSync(file)) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileAtomic(file, content);
  }
  return file;
}

export function readSourceText(
  workspace: WorkspaceInfo,
  intakeId: string,
  contentHash: string,
): string | undefined {
  const file = sourceFile(workspace, intakeId, contentHash);
  if (!existsSync(file)) return undefined;
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return undefined;
  }
}

export function writeSpecSource(workspace: WorkspaceInfo, source: SpecSource): SpecSource {
  const validated = specSourceSchema.parse(source);
  writeJson(intakePath(workspace, validated.intakeId, 'source.json'), validated);
  return validated;
}

export function readSpecSource(
  workspace: WorkspaceInfo,
  intakeId: string,
): SpecSource | undefined {
  return readJson(intakePath(workspace, intakeId, 'source.json'), (raw) =>
    specSourceSchema.parse(raw),
  );
}

export function requireSpecSource(workspace: WorkspaceInfo, intakeId: string): SpecSource {
  const source = readSpecSource(workspace, intakeId);
  if (source === undefined) {
    throw new IntakeError('SBI007', `Spec intake "${intakeId}" has no ingested source document.`, {
      remediation: ['Re-run `specbridge spec start <name> --file <spec-file>`.'],
      details: { intakeId },
    });
  }
  return source;
}

