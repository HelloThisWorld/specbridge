export function baselineFile(workspace: WorkspaceInfo): string {
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(intakeRootDir(workspace), 'baseline.json'),
  );
}

export function readProductBaseline(workspace: WorkspaceInfo): ProductBaseline {
  return (
    readJson(baselineFile(workspace), (raw) => productBaselineSchema.parse(raw)) ?? {
      schemaVersion: PRODUCT_BASELINE_SCHEMA_VERSION,
      updatedAt: '1970-01-01T00:00:00.000Z',
      features: [],
    }
  );
}

export function writeProductBaseline(
  workspace: WorkspaceInfo,
  baseline: ProductBaseline,
): ProductBaseline {
  const validated = productBaselineSchema.parse(baseline);
  writeJson(baselineFile(workspace), validated);
  return validated;
}

/** Bytes the stored source occupies, for reporting on a long specification. */
export function sourceByteLength(
  workspace: WorkspaceInfo,
  intakeId: string,
  contentHash: string,
): number | null {
  try {
    return statSync(sourceFile(workspace, intakeId, contentHash)).size;
  } catch {
    return null;
  }
}
