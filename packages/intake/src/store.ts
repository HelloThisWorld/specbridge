// ---------------------------------------------------------------------------
// The approval
// ---------------------------------------------------------------------------

export function approvalFile(workspace: WorkspaceInfo, intakeId: string): string {
  return intakePath(workspace, intakeId, 'approval.json');
}

/**
 * Write the human authorization. Refuses to overwrite an existing one.
 *
 * This is the immutability rule of the whole package: everything downstream
 * — the seal, the derived stage approvals, the launch — cites this record by
 * id and digest, and a record that could be edited afterwards would make
 * every one of those citations meaningless.
 */
export function writeApproval(workspace: WorkspaceInfo, approval: IntakeApproval): IntakeApproval {
  const validated = intakeApprovalSchema.parse(approval);
  const file = approvalFile(workspace, validated.intakeId);
  if (existsSync(file)) {
    throw new IntakeError(
      'SBI017',
      `Spec intake "${validated.intakeId}" is already approved; an approval is immutable.`,
      {
        remediation: [
          'Reopen discovery for a material change, which starts a new approval lifecycle.',
        ],
        details: { intakeId: validated.intakeId },
      },
    );
  }
  writeJson(file, validated);
  return validated;
}

export function readApproval(
  workspace: WorkspaceInfo,
  intakeId: string,
): IntakeApproval | undefined {
  return readJson(approvalFile(workspace, intakeId), (raw) => intakeApprovalSchema.parse(raw));
}

export function requireApproval(workspace: WorkspaceInfo, intakeId: string): IntakeApproval {
  const approval = readApproval(workspace, intakeId);
  if (approval === undefined) {
    throw new IntakeError('SBI011', `Spec intake "${intakeId}" has not been approved.`, {
      remediation: ['Approve it with `specbridge spec approve <name> --build`.'],
      details: { intakeId },
    });
  }
  return approval;
}

/**
 * Record the seal the approval produced.
 *
 * The one mutation an approval record accepts, and it is write-once: binding
 * a different seal to an existing approval would mean two authorizations
 * shared one human decision.
 */
export function bindApprovalSeal(
  workspace: WorkspaceInfo,
  intakeId: string,
  sealId: string,
): IntakeApproval {
  const approval = requireApproval(workspace, intakeId);
  if (approval.sealId !== undefined) {
    if (approval.sealId === sealId) return approval;
    throw new IntakeError(
      'SBI012',
      `Approval ${approval.approvalId} already authorized seal ${approval.sealId}.`,
      { details: { intakeId, existing: approval.sealId, attempted: sealId } },
    );
  }
  const bound = intakeApprovalSchema.parse({ ...approval, sealId });
  writeJson(approvalFile(workspace, intakeId), bound);
  return bound;
}

