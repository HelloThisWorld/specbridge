/**
 * Spec-intake persistence:
 *
 *   .specbridge/intake/
 *     baseline.json                      product baseline + feature lineage
 *     <intakeId>/
 *       intake.json                      the intake state
 *       source/<sha256>.md               the submitted specification, verbatim
 *       source.json                      provenance + deterministic chunk index
 *       grounding.json                   repository-grounded discovery report
 *       delta.json                       delta authority analysis
 *       questions.jsonl                  admitted product questions (fold by id)
 *       refusals.jsonl                   candidate questions declined, and why
 *       approval.json                    THE human authorization (immutable)
 *       projection.json                  projection equivalence verdict
 *       lifecycle.json                   the seal-and-build step ledger
 *       events.jsonl                     append-only intake history
 *
 * Same guarantees as every other SpecBridge state family: every path passes
 * `assertInsideWorkspace`, every write is atomic, and a corrupt record is
 * skipped by listings and left on disk for diagnosis rather than rewritten.
 *
 * Two rules specific to this family.
 *
 * THE SUBMITTED SPECIFICATION IS NEVER REWRITTEN. It is written once, under
 * a content-addressed name, and re-ingesting identical bytes is a no-op
 * rather than an overwrite. The original text is product evidence, and
 * evidence that can be edited in place is not evidence.
 *
 * THE APPROVAL IS IMMUTABLE. `writeApproval` refuses an existing path
 * outright. An authorization that can be edited is not an authorization; the
 * only field the lifecycle later adds is the seal id, and it does that
 * through `bindApprovalSeal`, which refuses to change one already set.
 */

const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

export const INTAKE_DIR_NAME = 'intake';

export function assertIntakeId(id: string): string {
  if (!ID_PATTERN.test(id)) {
    throw new IntakeError('SBI005', `Invalid spec intake id "${id}".`, {
      remediation: ['Ids are generated by SpecBridge; pass one returned by an intake operation.'],
      details: { id },
    });
  }
  return id;
}

export function intakeRootDir(workspace: WorkspaceInfo): string {
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(workspace.rootDir, '.specbridge', INTAKE_DIR_NAME),
  );
}

export function intakeDir(workspace: WorkspaceInfo, intakeId: string): string {
  assertIntakeId(intakeId);
  return assertInsideWorkspace(workspace.rootDir, path.join(intakeRootDir(workspace), intakeId));
}

function intakePath(workspace: WorkspaceInfo, intakeId: string, ...segments: string[]): string {
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(intakeDir(workspace, intakeId), ...segments),
  );
}

// ---------------------------------------------------------------------------
// Primitives
// ---------------------------------------------------------------------------

function writeJson(file: string, value: unknown): void {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, `${JSON.stringify(value, null, 2)}\n`);
}

function readJson<T>(file: string, parse: (raw: unknown) => T): T | undefined {
  if (!existsSync(file)) return undefined;
  try {
    return parse(JSON.parse(readFileSync(file, 'utf8')));
  } catch {
    return undefined;
  }
}

function appendJsonl(file: string, value: Record<string, unknown>): void {
  mkdirSync(path.dirname(file), { recursive: true });
  appendFileSync(file, `${JSON.stringify(value)}\n`, 'utf8');
}

/**
 * Read a JSONL log and fold by id, last record winning.
 *
 * The same append-only-with-fold shape the mission store uses for facts,
 * questions, and decisions: history is never rewritten, and the current view
 * is derived.
 */
function readFolded<T>(file: string, key: keyof T & string, parse: (raw: unknown) => T): T[] {
  if (!existsSync(file)) return [];
  const folded = new Map<string, T>();
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (line.trim().length === 0) continue;
    try {
      const value = parse(JSON.parse(line));
      folded.set(String(value[key]), value);
    } catch {
      // A corrupt line is skipped and left on disk. One bad append must not
      // make the whole discovery record unreadable.
    }
  }
  return [...folded.values()];
}

