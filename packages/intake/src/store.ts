export function intakeStateFile(workspace: WorkspaceInfo, intakeId: string): string {
  return intakePath(workspace, intakeId, 'intake.json');
}

export function readIntakeState(
  workspace: WorkspaceInfo,
  intakeId: string,
): SpecIntakeState | undefined {
  return readJson(intakeStateFile(workspace, intakeId), (raw) => specIntakeStateSchema.parse(raw));
}

export function requireIntakeState(workspace: WorkspaceInfo, intakeId: string): SpecIntakeState {
  const state = readIntakeState(workspace, intakeId);
  if (state === undefined) {
    throw new IntakeError('SBI001', `No spec intake "${intakeId}" exists in this workspace.`, {
      remediation: ['List intakes with `specbridge spec intake`.'],
      details: { intakeId },
    });
  }
  return state;
}

export function writeIntakeState(
  workspace: WorkspaceInfo,
  state: SpecIntakeState,
): SpecIntakeState {
  const validated = specIntakeStateSchema.parse(state);
  writeJson(intakeStateFile(workspace, validated.intakeId), validated);
  return validated;
}

export interface IntakeListResult {
  intakes: SpecIntakeState[];
  /** Directories that exist but could not be read, surfaced not swallowed. */
  diagnostics: { intakeId: string; message: string }[];
}

export function listIntakes(workspace: WorkspaceInfo): IntakeListResult {
  const root = intakeRootDir(workspace);
  if (!existsSync(root)) return { intakes: [], diagnostics: [] };
  const intakes: SpecIntakeState[] = [];
  const diagnostics: IntakeListResult['diagnostics'] = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (!ID_PATTERN.test(entry.name)) continue;
    const file = path.join(root, entry.name, 'intake.json');
    if (!existsSync(file)) continue;
    try {
      intakes.push(specIntakeStateSchema.parse(JSON.parse(readFileSync(file, 'utf8'))));
    } catch (cause) {
      diagnostics.push({
        intakeId: entry.name,
        message: `intake state is unreadable: ${cause instanceof Error ? cause.message : String(cause)}`,
      });
    }
  }
  intakes.sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  return { intakes, diagnostics };
}

/**
 * Resolve a subject to one intake: an intake id, an intake name, a mission
 * id, or a synthesized spec name.
 *
 * Names win over ids only when no id matches, and the NEWEST non-abandoned
 * match wins among equals — a user who runs `spec start airport-demo` twice
 * means the second one.
 */
export function findIntake(
  workspace: WorkspaceInfo,
  subject: string,
): SpecIntakeState | undefined {
  const { intakes } = listIntakes(workspace);
  const byId = intakes.find((intake) => intake.intakeId === subject);
  if (byId !== undefined) return byId;
  const candidates = intakes.filter(
    (intake) =>
      intake.name === subject ||
      intake.missionId === subject ||
      intake.specName === subject,
  );
  const live = candidates.filter((intake) => intake.status !== 'ABANDONED');
  const pool = live.length > 0 ? live : candidates;
  return pool.length === 0 ? undefined : pool[pool.length - 1];
}

