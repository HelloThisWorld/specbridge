// ---------------------------------------------------------------------------
// ADRs (immutable files)
// ---------------------------------------------------------------------------

export function storeAdr(workspace: WorkspaceInfo, missionId: string, adr: MissionAdr): string {
  const validated = missionAdrSchema.parse(adr);
  if (!ID_PATTERN.test(validated.adrId)) {
    throw new MissionError('SBM005', `Invalid ADR id "${validated.adrId}".`);
  }
  const file = artifactPath(workspace, missionId, 'adrs', `${validated.adrId}.json`);
  if (existsSync(file)) {
    throw new MissionError(
      'SBM010',
      `ADR ${validated.adrId} already exists; ADR files are immutable. Record a superseding ADR instead.`,
    );
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, `${JSON.stringify(validated, null, 2)}\n`);
  return file;
}

/**
 * All ADRs with DERIVED effective status: an ADR is superseded exactly when
 * a later ADR names it in `supersedes`. Files are never rewritten.
 */
export function readAdrs(workspace: WorkspaceInfo, missionId: string): MissionAdr[] {
  const dir = artifactPath(workspace, missionId, 'adrs');
  if (!existsSync(dir)) return [];
  const adrs: MissionAdr[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (!name.endsWith('.json')) continue;
    try {
      const result = missionAdrSchema.safeParse(
        JSON.parse(readFileSync(path.join(dir, name), 'utf8')),
      );
      if (result.success) adrs.push(result.data);
    } catch {
      // An unreadable ADR is skipped from views; the file is preserved.
    }
  }
  const superseded = new Set(
    adrs.map((adr) => adr.supersedes).filter((id): id is string => id !== undefined),
  );
  return adrs.map((adr) =>
    superseded.has(adr.adrId) ? { ...adr, status: 'superseded' as const } : adr,
  );
}

export function readAdr(
  workspace: WorkspaceInfo,
  missionId: string,
  adrId: string,
): MissionAdr | undefined {
  return readAdrs(workspace, missionId).find((adr) => adr.adrId === adrId);
}

// ---------------------------------------------------------------------------
// Contract registry (immutable per-revision files)
// ---------------------------------------------------------------------------

function contractFileName(contractId: string, revision: number): string {
  return `${contractId}-r${String(revision).padStart(3, '0')}.json`;
}

export function storeContractRevision(
  workspace: WorkspaceInfo,
  missionId: string,
  contract: ProductContract,
): string {
  const validated = productContractSchema.parse(contract);
  if (!ID_PATTERN.test(validated.contractId)) {
    throw new MissionError('SBM005', `Invalid contract id "${validated.contractId}".`);
  }
  const file = artifactPath(
    workspace,
    missionId,
    'contracts',
    contractFileName(validated.contractId, validated.revision),
  );
  if (existsSync(file)) {
    throw new MissionError(
      'SBM010',
      `Contract ${validated.contractId} revision ${validated.revision} already exists; revisions are immutable.`,
    );
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, `${JSON.stringify(validated, null, 2)}\n`);
  return file;
}

/** Every stored contract revision, ascending by (contractId, revision). */
export function readContractRevisions(
  workspace: WorkspaceInfo,
  missionId: string,
): ProductContract[] {
  const dir = artifactPath(workspace, missionId, 'contracts');
  if (!existsSync(dir)) return [];
  const contracts: ProductContract[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (!name.endsWith('.json')) continue;
    try {
      const result = productContractSchema.safeParse(
        JSON.parse(readFileSync(path.join(dir, name), 'utf8')),
      );
      if (result.success) contracts.push(result.data);
    } catch {
      // Unreadable revisions are skipped from views and preserved on disk.
    }
  }
  contracts.sort(
    (a, b) => a.contractId.localeCompare(b.contractId, 'en') || a.revision - b.revision,
  );
  return contracts;
}

/**
 * The current registry view: the highest revision per contract id, with
 * superseded revisions' status derived.
 */
export function readContractRegistry(
  workspace: WorkspaceInfo,
  missionId: string,
): ProductContract[] {
  const byId = new Map<string, ProductContract>();
  for (const revision of readContractRevisions(workspace, missionId)) {
    const current = byId.get(revision.contractId);
    if (current === undefined || revision.revision > current.revision) {
      byId.set(revision.contractId, revision);
    }
  }
  return [...byId.values()].sort((a, b) => a.contractId.localeCompare(b.contractId, 'en'));
}

export function readContract(
  workspace: WorkspaceInfo,
  missionId: string,
  contractId: string,
  revision?: number,
): ProductContract | undefined {
  if (revision !== undefined) {
    return readContractRevisions(workspace, missionId).find(
      (contract) => contract.contractId === contractId && contract.revision === revision,
    );
  }
  return readContractRegistry(workspace, missionId).find(
    (contract) => contract.contractId === contractId,
  );
}

