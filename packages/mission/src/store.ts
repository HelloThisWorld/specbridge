export type MissionReadResult =
  | { kind: 'ok'; mission: MissionState }
  | { kind: 'missing' }
  | { kind: 'corrupt'; problem: string; file: string }
  | { kind: 'unsupported-version'; version: string; file: string };

export function readMissionState(workspace: WorkspaceInfo, missionId: string): MissionReadResult {
  const file = artifactPath(workspace, missionId, 'mission.json');
  if (!existsSync(file)) return { kind: 'missing' };
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(file, 'utf8'));
  } catch (cause) {
    return { kind: 'corrupt', problem: cause instanceof Error ? cause.message : String(cause), file };
  }
  const declared =
    parsed !== null && typeof parsed === 'object'
      ? (parsed as { schemaVersion?: unknown }).schemaVersion
      : undefined;
  if (typeof declared !== 'string') {
    return { kind: 'corrupt', problem: 'schemaVersion is missing', file };
  }
  if (majorOf(declared) !== majorOf(MISSION_STATE_SCHEMA_VERSION)) {
    return { kind: 'unsupported-version', version: declared, file };
  }
  const result = missionStateSchema.safeParse(parsed);
  if (!result.success) {
    return {
      kind: 'corrupt',
      problem: result.error.issues
        .map((issue) => `${issue.path.join('.') || '(root)'}: ${issue.message}`)
        .join('; '),
      file,
    };
  }
  return { kind: 'ok', mission: result.data };
}

export function requireMissionState(workspace: WorkspaceInfo, missionId: string): MissionState {
  const read = readMissionState(workspace, missionId);
  switch (read.kind) {
    case 'ok':
      return read.mission;
    case 'missing':
      throw new MissionError(
        'SBM001',
        `Mission "${missionId}" was not found under .specbridge/${MISSIONS_DIR_NAME}/.`,
        { remediation: ['List missions with `specbridge mission status --json`.'] },
      );
    case 'corrupt':
      throw new MissionError(
        'SBM002',
        `Mission "${missionId}" has unreadable state: ${read.problem}. The file was left untouched for diagnosis.`,
        {
          remediation: [
            `Inspect ${read.file}.`,
            'Begin a new mission; the corrupt record is never rewritten automatically.',
          ],
          details: { file: read.file },
        },
      );
    case 'unsupported-version':
      throw new MissionError(
        'SBM002',
        `Mission "${missionId}" was written by a newer SpecBridge (schema ${read.version}); ` +
          `this build reads ${MISSION_STATE_SCHEMA_VERSION}.`,
        {
          remediation: ['Upgrade SpecBridge, or begin a new mission with this version.'],
          details: { file: read.file, version: read.version },
        },
      );
  }
}

export function writeMissionState(workspace: WorkspaceInfo, mission: MissionState): MissionState {
  const validated = missionStateSchema.parse(mission);
  const dir = missionDir(workspace, validated.missionId);
  mkdirSync(dir, { recursive: true });
  writeFileAtomic(path.join(dir, 'mission.json'), `${JSON.stringify(validated, null, 2)}\n`);
  return validated;
}

export function initializeMissionRecord(
  workspace: WorkspaceInfo,
  mission: MissionState,
): MissionState {
  const dir = missionDir(workspace, mission.missionId);
  if (existsSync(dir)) {
    throw new MissionError('SBM010', `Mission directory already exists: ${dir}. Ids must be unique.`);
  }
  mkdirSync(path.join(dir, 'adrs'), { recursive: true });
  mkdirSync(path.join(dir, 'contracts'), { recursive: true });
  mkdirSync(path.join(dir, 'ccrs'), { recursive: true });
  mkdirSync(path.join(dir, 'spec-candidates'), { recursive: true });
  return writeMissionState(workspace, mission);
}

export interface MissionListResult {
  missions: MissionState[];
  diagnostics: Diagnostic[];
}

/** All missions, newest first. Unreadable records become diagnostics. */
export function listMissions(workspace: WorkspaceInfo): MissionListResult {
  const root = missionsRootDir(workspace);
  if (!existsSync(root)) return { missions: [], diagnostics: [] };
  const missions: MissionState[] = [];
  const diagnostics: Diagnostic[] = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (!ID_PATTERN.test(entry.name)) continue;
    const read = readMissionState(workspace, entry.name);
    if (read.kind === 'ok') {
      missions.push(read.mission);
      continue;
    }
    if (read.kind === 'missing') continue;
    diagnostics.push({
      severity: 'warning',
      code:
        read.kind === 'unsupported-version'
          ? 'MISSION_STATE_UNSUPPORTED_VERSION'
          : 'MISSION_STATE_UNREADABLE',
      message:
        read.kind === 'unsupported-version'
          ? `Mission ${entry.name} uses state schema ${read.version}; ignoring it.`
          : `Mission ${entry.name} has unreadable state; ignoring it.`,
      file: read.file,
    });
  }
  missions.sort(
    (a, b) =>
      b.createdAt.localeCompare(a.createdAt, 'en') || b.missionId.localeCompare(a.missionId, 'en'),
  );
  return { missions, diagnostics };
}

/** The mission that synthesized `specName`, when exactly one exists. */
export function findMissionForSpec(
  workspace: WorkspaceInfo,
  specName: string,
): MissionState | undefined {
  const { missions } = listMissions(workspace);
  const matches = missions.filter((mission) => mission.specName === specName);
  // Two missions claiming one spec would be ambiguous provenance; refuse to
  // guess and treat the spec as not mission-driven.
  return matches.length === 1 ? matches[0] : undefined;
}

// ---------------------------------------------------------------------------
// Append-only jsonl histories with fold-by-id current views
// ---------------------------------------------------------------------------

function appendJsonl(
  workspace: WorkspaceInfo,
  missionId: string,
  fileName: string,
  record: Record<string, unknown>,
  limits: { maxRecordBytes: number },
): void {
  const line = `${JSON.stringify(record)}\n`;
  if (Buffer.byteLength(line, 'utf8') > limits.maxRecordBytes) {
    throw new MissionError(
      'SBM006',
      `A ${fileName} record is larger than the ${limits.maxRecordBytes}-byte limit and was not recorded.`,
      { remediation: ['Mission records are bounded summaries; keep them short.'] },
    );
  }
  const file = artifactPath(workspace, missionId, fileName);
  mkdirSync(path.dirname(file), { recursive: true });
  appendFileSync(file, line, 'utf8');
}

function readJsonl(workspace: WorkspaceInfo, missionId: string, fileName: string): unknown[] {
  const file = artifactPath(workspace, missionId, fileName);
  if (!existsSync(file)) return [];
  let raw: string;
  try {
    raw = readFileSync(file, 'utf8');
  } catch {
    return [];
  }
  const records: unknown[] = [];
  for (const line of raw.split('\n')) {
    if (line.trim().length === 0) continue;
    try {
      records.push(JSON.parse(line));
    } catch {
      // A partially written final line (crash during append) is skipped; the
      // rest of the history stays readable.
    }
  }
  return records;
}

/** Fold an append-only history to its current view: last record per id wins. */
function foldById<T>(records: T[], idOf: (record: T) => string): T[] {
  const byId = new Map<string, T>();
  for (const record of records) byId.set(idOf(record), record);
  return [...byId.values()];
}

const RECORD_LIMITS = { maxRecordBytes: 32_768 } as const;

// --- Turns ---

export function appendTurn(workspace: WorkspaceInfo, missionId: string, turn: ConversationTurn): void {
  appendJsonl(workspace, missionId, 'conversation.jsonl', conversationTurnSchema.parse(turn), RECORD_LIMITS);
}

export interface TurnPage {
  turns: ConversationTurn[];
  total: number;
  truncated: boolean;
}

/** Read a bounded page of turns, newest last. Never unbounded. */
export function readTurns(
  workspace: WorkspaceInfo,
  missionId: string,
  options: { limit?: number; offset?: number } = {},
): TurnPage {
  const parsed: ConversationTurn[] = [];
  for (const record of readJsonl(workspace, missionId, 'conversation.jsonl')) {
    const result = conversationTurnSchema.safeParse(record);
    if (result.success) parsed.push(result.data);
  }
  const limit = Math.max(1, Math.min(options.limit ?? 50, 500));
  const offset = Math.max(0, options.offset ?? 0);
  const window = parsed.slice(Math.max(0, parsed.length - offset - limit), parsed.length - offset);
  return { turns: window, total: parsed.length, truncated: parsed.length > window.length };
}

export function findTurn(
  workspace: WorkspaceInfo,
  missionId: string,
  turnId: string,
): ConversationTurn | undefined {
  for (const record of readJsonl(workspace, missionId, 'conversation.jsonl')) {
    const result = conversationTurnSchema.safeParse(record);
    if (result.success && result.data.turnId === turnId) return result.data;
  }
  return undefined;
}

