/**
 * Mission persistence: `.specbridge/missions/<missionId>/`.
 *
 *   mission.json          the versioned mission state (atomic, last-writer view)
 *   events.jsonl          append-only history
 *   conversation.jsonl    append-only visible discovery turns
 *   facts.jsonl           append-only fact records; current view folds by id
 *   questions.jsonl       append-only question records; current view folds by id
 *   decisions.jsonl       append-only decision records; current view folds by id
 *   coverage.json         the computed coverage snapshot (atomic rewrite)
 *   constitution.json     the constitution (atomic rewrite; rules keep history in-file)
 *   adrs/ADR-####.json    immutable ADR files
 *   contracts/CTR-####-r###.json  immutable per-revision contract files
 *   ccrs/CCR-####.json    contract change requests (service-controlled rewrites)
 *   spec-candidates/      synthesized stage candidates + provenance map
 *   checkpoint.json       the latest structured checkpoint
 *
 * Guarantees, all exercised by tests:
 *   - every path passes assertInsideWorkspace (no traversal, no symlink escape)
 *   - every JSON write is atomic (temp + fsync + rename)
 *   - jsonl histories are append-only; corrections append superseding records
 *   - a corrupt or unknown-major-version record fails safely and is preserved
 *     for diagnosis, never silently rewritten or deleted
 *   - reads never mutate state
 *   - `.kiro` is never touched: mission state is runtime metadata and lives
 *     entirely inside the `.specbridge` sidecar
 */

export const MISSIONS_DIR_NAME = 'missions';

/** Ids are generated by SpecBridge; the pattern is enforced on every path. */
const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

export function missionsRootDir(workspace: WorkspaceInfo): string {
  return path.join(workspace.sidecarDir, MISSIONS_DIR_NAME);
}

export function assertMissionId(missionId: string): string {
  if (!ID_PATTERN.test(missionId)) {
    throw new MissionError('SBM001', `Invalid mission id "${missionId}".`, {
      remediation: ['Ids are generated by SpecBridge; pass one returned by a mission operation.'],
    });
  }
  return missionId;
}

export function missionDir(workspace: WorkspaceInfo, missionId: string): string {
  assertMissionId(missionId);
  return assertInsideWorkspace(workspace.rootDir, path.join(missionsRootDir(workspace), missionId));
}

function artifactPath(workspace: WorkspaceInfo, missionId: string, ...segments: string[]): string {
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(missionDir(workspace, missionId), ...segments),
  );
}

function majorOf(version: string): string {
  return version.split('.')[0] ?? '';
}

