export interface MissionEventPage {
  events: MissionEvent[];
  total: number;
  truncated: boolean;
}

export function readMissionEvents(
  workspace: WorkspaceInfo,
  missionId: string,
  options: { limit?: number; offset?: number } = {},
): MissionEventPage {
  const parsed = readJsonl(workspace, missionId, 'events.jsonl').filter(
    (record): record is MissionEvent => record !== null && typeof record === 'object',
  );
  const limit = Math.max(1, Math.min(options.limit ?? 50, 500));
  const offset = Math.max(0, options.offset ?? 0);
  const window = parsed.slice(Math.max(0, parsed.length - offset - limit), parsed.length - offset);
  return { events: window, total: parsed.length, truncated: parsed.length > window.length };
}

export function countMissionEvents(workspace: WorkspaceInfo, missionId: string): number {
  return readJsonl(workspace, missionId, 'events.jsonl').length;
}

