/**
 * Persist a selection plan for explainability.
 *
 * The plan carries paths, hashes, ranges, and reasons — never file bodies
 * (see `ContextSelectionPlan`). That is what makes this record safe to keep
 * and safe to print, and it is why the store does not need its own redaction
 * pass: there is nothing here to redact.
 */
export function writeContextSelectionPlan(
  workspace: WorkspaceInfo,
  plan: ContextSelectionPlan,
): ContextSelectionPlan {
  const validated = contextSelectionPlanSchema.parse(plan);
  if (validated.jobId === undefined) return validated;
  const file = planFile(workspace, validated.jobId, validated.planId);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, `${JSON.stringify(validated, null, 2)}\n`);
  return validated;
}

