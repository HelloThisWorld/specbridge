import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import type { WorkspaceInfo } from '@specbridge/core';
import { assertInsideWorkspace, writeFileAtomic } from '@specbridge/core';
import type {
  ContextEfficiencyMetrics,
  ContextExpansionState,
  ContextSelectionPlan,
  RepositoryContextIndexState,
} from '@specbridge/context';
import {
  contextEfficiencyMetricsSchema,
  contextExpansionStateSchema,
  contextSelectionPlanSchema,
  repositoryContextIndexSchema,
} from '@specbridge/context';
import { OrchestrationError } from '../errors.js';
import { jobDir } from '../jobs/store.js';

/**
 * Context-efficiency persistence.
 *
 *   .specbridge/cache/context-index.json          derived repository index
 *   .specbridge/jobs/<jobId>/context/
 *     expansion/<nodeId>.json                     bounded widening budget
 *     plans/<planId>.json                         selection plans (explain)
 *     metrics/<attemptId>.json                    per-attempt efficiency facts
 *
 * The split between `cache/` and `jobs/` is the whole design in one
 * directory layout:
 *
 *   `cache/` is DISPOSABLE. The repository index is derived from bytes on
 *   disk; deleting it costs a rebuild and nothing else. Job recovery must
 *   never depend on it, which is why it lives outside the job namespace
 *   entirely — a path that makes "delete the cache" an obviously safe
 *   operation rather than a judgement call.
 *
 *   `jobs/<jobId>/context/` is JOB-SCOPED derived state. The expansion budget
 *   has to survive a restart or the bound it enforces would reset every time
 *   a process died — which would turn a bounded widening policy into an
 *   unbounded one. Plans and metrics live beside it for explainability, and
 *   losing any of them degrades diagnostics without touching correctness.
 *
 * Every write is atomic and every path passes `assertInsideWorkspace`, the
 * same discipline the survival and reliability stores already use. Corrupt
 * records are SKIPPED and preserved for diagnosis, never rewritten.
 */

const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/;

function assertRecordId(kind: string, id: string): string {
  if (!ID_PATTERN.test(id)) {
    throw new OrchestrationError('SBO049', `Invalid context ${kind} id "${id}".`, {
      remediation: ['Ids are generated by SpecBridge; pass one returned by a context operation.'],
    });
  }
  return id;
}

// ---------------------------------------------------------------------------
// Repository index cache (disposable)
// ---------------------------------------------------------------------------

export function contextCacheDir(workspace: WorkspaceInfo): string {
  return assertInsideWorkspace(workspace.rootDir, path.join(workspace.sidecarDir, 'cache'));
}

export function repositoryIndexFile(workspace: WorkspaceInfo): string {
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(contextCacheDir(workspace), 'context-index.json'),
  );
}

/**
 * Read the persisted index, or undefined when it is absent, unreadable, or
 * schema-invalid.
 *
 * Every failure mode collapses to the same answer — undefined, meaning
 * "rebuild" — deliberately. There is no state of this file that is worth
 * partially trusting, and a caller that had to distinguish "missing" from
 * "corrupt" would eventually be tempted to use the corrupt one.
 */
export function readRepositoryIndexCache(
  workspace: WorkspaceInfo,
): RepositoryContextIndexState | undefined {
  const file = repositoryIndexFile(workspace);
  if (!existsSync(file)) return undefined;
  try {
    const parsed = repositoryContextIndexSchema.safeParse(JSON.parse(readFileSync(file, 'utf8')));
    return parsed.success ? parsed.data : undefined;
  } catch {
    return undefined;
  }
}

export function writeRepositoryIndexCache(
  workspace: WorkspaceInfo,
  state: RepositoryContextIndexState,
): void {
  const validated = repositoryContextIndexSchema.parse(state);
  const file = repositoryIndexFile(workspace);
  mkdirSync(path.dirname(file), { recursive: true });
  // No pretty-printing: this file is machine state that can hold tens of
  // thousands of entries, and indentation would triple it for nobody.
  writeFileAtomic(file, `${JSON.stringify(validated)}\n`);
}

/** Delete the derived index. Always safe: job state never depends on it. */
export function clearRepositoryIndexCache(workspace: WorkspaceInfo): void {
  const file = repositoryIndexFile(workspace);
  if (existsSync(file)) rmSync(file, { force: true });
}

