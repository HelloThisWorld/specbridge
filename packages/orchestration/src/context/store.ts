export interface ListContextPlansOptions {
  nodeId?: string | undefined;
  attemptId?: string | undefined;
}

/** Selection plans for a job, oldest first. Corrupt records are skipped. */
export function listContextSelectionPlans(
  workspace: WorkspaceInfo,
  jobId: string,
  options: ListContextPlansOptions = {},
): ContextSelectionPlan[] {
  const dir = path.join(jobContextDir(workspace, jobId), 'plans');
  if (!existsSync(dir)) return [];
  const plans: ContextSelectionPlan[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.json')) continue;
    try {
      const parsed = contextSelectionPlanSchema.safeParse(
        JSON.parse(readFileSync(path.join(dir, entry.name), 'utf8')),
      );
      if (!parsed.success) continue;
      if (options.nodeId !== undefined && parsed.data.nodeId !== options.nodeId) continue;
      if (options.attemptId !== undefined && parsed.data.attemptId !== options.attemptId) continue;
      plans.push(parsed.data);
    } catch {
      continue;
    }
  }
  return plans.sort((left, right) =>
    left.createdAt === right.createdAt
      ? left.planId < right.planId
        ? -1
        : 1
      : left.createdAt < right.createdAt
        ? -1
        : 1,
  );
}

