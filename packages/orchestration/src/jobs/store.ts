/**
 * Persist one node-plan revision (a v1.1 ExecutionPlan document bound to the
 * node's approved task). Append-only, exactly like graph revisions.
 */
export function storeNodePlan(
  workspace: WorkspaceInfo,
  jobId: string,
  nodeId: string,
  revision: number,
  plan: Record<string, unknown>,
): { file: string } {
  if (!ID_PATTERN.test(nodeId)) {
    throw new OrchestrationError('SBO031', `Invalid node id "${nodeId}".`);
  }
  const file = artifactPath(
    workspace,
    jobId,
    'plans',
    `${nodeId}-${String(revision).padStart(4, '0')}.json`,
  );
  if (existsSync(file)) {
    throw new OrchestrationError('SBO031', `Plan revision ${revision} for node ${nodeId} already exists.`);
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, `${JSON.stringify(plan, null, 2)}\n`);
  return { file };
}

export function readNodePlan(
  workspace: WorkspaceInfo,
  jobId: string,
  nodeId: string,
  revision: number,
): Record<string, unknown> | undefined {
  if (!ID_PATTERN.test(nodeId) || !Number.isInteger(revision) || revision < 1) return undefined;
  const file = artifactPath(
    workspace,
    jobId,
    'plans',
    `${nodeId}-${String(revision).padStart(4, '0')}.json`,
  );
  if (!existsSync(file)) return undefined;
  try {
    const parsed: unknown = JSON.parse(readFileSync(file, 'utf8'));
    return parsed !== null && typeof parsed === 'object'
      ? (parsed as Record<string, unknown>)
      : undefined;
  } catch {
    return undefined;
  }
}

