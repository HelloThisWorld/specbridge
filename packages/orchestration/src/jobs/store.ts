/**
 * Persist one bounded structured agent result and return its reference.
 *
 * The caller passes an ALREADY-VALIDATED structured document (see
 * agents/contracts.ts); this layer enforces the size bound and the naming
 * scheme. Results are append-only: a name collision is refused, never
 * overwritten.
 */
export function storeAgentResult(
  workspace: WorkspaceInfo,
  jobId: string,
  name: string,
  document: Record<string, unknown>,
  limits: { maxBytes: number },
): { ref: string; file: string } {
  if (!AGENT_RESULT_NAME_PATTERN.test(name)) {
    throw new OrchestrationError('SBO037', `Invalid agent result name "${name}".`);
  }
  const serialized = `${JSON.stringify(document, null, 2)}\n`;
  if (Buffer.byteLength(serialized, 'utf8') > limits.maxBytes) {
    throw new OrchestrationError(
      'SBO037',
      `The agent result "${name}" exceeds the ${limits.maxBytes}-byte limit and was not stored.`,
      { remediation: ['Structured agent results are summaries; keep them bounded.'] },
    );
  }
  const file = artifactPath(workspace, jobId, 'agents', name);
  if (existsSync(file)) {
    throw new OrchestrationError('SBO037', `Agent result "${name}" already exists; results are append-only.`);
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, serialized);
  return { ref: `agents/${name}`, file };
}

/** Read one stored agent result by its recorded reference. */
export function readAgentResult(
  workspace: WorkspaceInfo,
  jobId: string,
  ref: string,
): Record<string, unknown> | undefined {
  const name = ref.startsWith('agents/') ? ref.slice('agents/'.length) : ref;
  if (!AGENT_RESULT_NAME_PATTERN.test(name)) return undefined;
  const file = artifactPath(workspace, jobId, 'agents', name);
  if (!existsSync(file)) return undefined;
  try {
    const parsed: unknown = JSON.parse(readFileSync(file, 'utf8'));
    return parsed !== null && typeof parsed === 'object'
      ? (parsed as Record<string, unknown>)
      : undefined;
  } catch {
    return undefined;
  }
}

// ---------------------------------------------------------------------------
// Events
// ---------------------------------------------------------------------------

export interface JobEvent extends Record<string, unknown> {
  at: string;
  type: JobEventType;
}

/**
 * Append one bounded event. Oversized payloads are refused rather than
 * truncated, exactly like the v1.1 event log.
 */
export function appendJobEvent(
  workspace: WorkspaceInfo,
  jobId: string,
  event: JobEvent,
  limits: { maxEventBytes: number },
): void {
  const line = `${JSON.stringify(event)}\n`;
  if (Buffer.byteLength(line, 'utf8') > limits.maxEventBytes) {
    throw new OrchestrationError(
      'SBO021',
      `Job event of type "${event.type}" is larger than the configured ` +
        `${limits.maxEventBytes}-byte limit and was not recorded.`,
      { remediation: ['Record a shorter summary; full evidence lives in the run directory.'] },
    );
  }
  const file = artifactPath(workspace, jobId, 'events.jsonl');
  mkdirSync(path.dirname(file), { recursive: true });
  appendFileSync(file, line, 'utf8');
}

export interface JobEventPage {
  events: JobEvent[];
  total: number;
  truncated: boolean;
}

/** Read a bounded page of events, newest last. Never unbounded. */
export function readJobEvents(
  workspace: WorkspaceInfo,
  jobId: string,
  options: { limit?: number; offset?: number } = {},
): JobEventPage {
  const file = artifactPath(workspace, jobId, 'events.jsonl');
  if (!existsSync(file)) return { events: [], total: 0, truncated: false };
  let raw: string;
  try {
    raw = readFileSync(file, 'utf8');
  } catch {
    return { events: [], total: 0, truncated: false };
  }
  const lines = raw.split('\n').filter((line) => line.trim().length > 0);
  const parsed: JobEvent[] = [];
  for (const line of lines) {
    try {
      const value: unknown = JSON.parse(line);
      if (value !== null && typeof value === 'object') parsed.push(value as JobEvent);
    } catch {
      // A partially written final line (crash during append) is skipped, not
      // fatal: the rest of the history stays readable.
    }
  }
  const limit = Math.max(1, Math.min(options.limit ?? 50, 500));
  const offset = Math.max(0, options.offset ?? 0);
  const window = parsed.slice(Math.max(0, parsed.length - offset - limit), parsed.length - offset);
  return { events: window, total: parsed.length, truncated: parsed.length > window.length };
}

export function countJobEvents(workspace: WorkspaceInfo, jobId: string): number {
  const file = artifactPath(workspace, jobId, 'events.jsonl');
  if (!existsSync(file)) return 0;
  try {
    return readFileSync(file, 'utf8')
      .split('\n')
      .filter((line) => line.trim().length > 0).length;
  } catch {
    return 0;
  }
}

