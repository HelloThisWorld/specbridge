const ARTIFACT_NAME_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

/**
 * Write one generated release artifact into the run directory.
 *
 * The name is validated against the same pattern as a record id: report
 * generation must never be a path-traversal surface, even when the caller is
 * the CLI and the name looks like a constant.
 */
export function writeQualificationArtifact(
  workspace: WorkspaceInfo,
  runId: string,
  name: string,
  contents: string,
): string {
  if (!ARTIFACT_NAME_PATTERN.test(name)) {
    throw new OrchestrationError('SBO052', `Invalid qualification artifact name "${name}".`, {
      remediation: ['Artifact names are generated by SpecBridge and contain no path separators.'],
    });
  }
  const file = assertInsideWorkspace(
    workspace.rootDir,
    path.join(recordDir(workspace, runId, 'reports'), name),
  );
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, contents);
  return file;
}

export function qualificationArtifactPath(
  workspace: WorkspaceInfo,
  runId: string,
  name: string,
): string {
  if (!ARTIFACT_NAME_PATTERN.test(name)) {
    throw new OrchestrationError('SBO052', `Invalid qualification artifact name "${name}".`);
  }
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(recordDir(workspace, runId, 'reports'), name),
  );
}
