/** Mark a persisted decision as acted upon. Identity and contents are kept. */
export function markRecoveryDecisionApplied(
  workspace: WorkspaceInfo,
  jobId: string,
  decisionId: string,
): RecoveryDecision | undefined {
  const decision = readRecoveryDecision(workspace, jobId, decisionId);
  if (decision === undefined) return undefined;
  const applied = recoveryDecisionSchema.parse({ ...decision, applied: true });
  writeRecord(recordFile(workspace, jobId, 'decisions', decisionId), applied);
  return applied;
}

// ---------------------------------------------------------------------------
// Per-task reliability state
// ---------------------------------------------------------------------------

function taskStateFile(workspace: WorkspaceInfo, jobId: string, nodeId: string): string {
  assertRecordId('node', nodeId);
  return assertInsideWorkspace(
    workspace.rootDir,
    path.join(recordDir(workspace, jobId, 'tasks'), `${nodeId}.json`),
  );
}

export function readTaskReliabilityState(
  workspace: WorkspaceInfo,
  jobId: string,
  nodeId: string,
): TaskReliabilityState | undefined {
  return readRecord(taskStateFile(workspace, jobId, nodeId), (raw) =>
    taskReliabilityStateSchema.parse(raw),
  );
}

/**
 * Read the task's reliability state, or an empty one.
 *
 * A task with no history is HEALTHY with an empty window — never a missing
 * value the callers would each have to remember to handle. Loop detection
 * over an empty window trivially reports no loop, which is correct.
 */
export function requireTaskReliabilityState(
  workspace: WorkspaceInfo,
  jobId: string,
  nodeId: string,
  taskId: string,
  at: string,
): TaskReliabilityState {
  return (
    readTaskReliabilityState(workspace, jobId, nodeId) ??
    taskReliabilityStateSchema.parse({
      schemaVersion: TASK_RELIABILITY_SCHEMA_VERSION,
      jobId,
      nodeId,
      taskId,
      updatedAt: at,
    })
  );
}

export function writeTaskReliabilityState(
  workspace: WorkspaceInfo,
  state: TaskReliabilityState,
): TaskReliabilityState {
  const validated = taskReliabilityStateSchema.parse(state);
  writeRecord(taskStateFile(workspace, validated.jobId, validated.nodeId), validated);
  return validated;
}

export function listTaskReliabilityStates(
  workspace: WorkspaceInfo,
  jobId: string,
): TaskReliabilityState[] {
  return listRecords(workspace, jobId, 'tasks', (raw) => taskReliabilityStateSchema.parse(raw));
}
