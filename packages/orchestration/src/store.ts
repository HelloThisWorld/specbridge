/** Persist one plan revision. Revisions are append-only: nothing is replaced. */
export function storePlanRevision(
  workspace: WorkspaceInfo,
  orchestrationId: string,
  plan: ExecutionPlan,
): { plan: ExecutionPlan; hash: string; file: string } {
  const validated = executionPlanSchema.parse(plan);
  const file = artifactPath(
    workspace,
    orchestrationId,
    'plans',
    `${String(validated.revision).padStart(4, '0')}.json`,
  );
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileAtomic(file, `${JSON.stringify(validated, null, 2)}\n`);
  return { plan: validated, hash: planHash(validated), file };
}

export function readPlanRevision(
  workspace: WorkspaceInfo,
  orchestrationId: string,
  revision: number,
): ExecutionPlan | undefined {
  if (!Number.isInteger(revision) || revision < 1) return undefined;
  const file = artifactPath(
    workspace,
    orchestrationId,
    'plans',
    `${String(revision).padStart(4, '0')}.json`,
  );
  if (!existsSync(file)) return undefined;
  try {
    const result = executionPlanSchema.safeParse(JSON.parse(readFileSync(file, 'utf8')));
    return result.success ? result.data : undefined;
  } catch {
    return undefined;
  }
}

/** Every stored plan revision, oldest first (bounded by the caller). */
export function listPlanRevisions(
  workspace: WorkspaceInfo,
  orchestrationId: string,
): ExecutionPlan[] {
  const dir = artifactPath(workspace, orchestrationId, 'plans');
  if (!existsSync(dir)) return [];
  const plans: ExecutionPlan[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (!/^\d{4}\.json$/.test(name)) continue;
    const revision = Number.parseInt(name.slice(0, 4), 10);
    const plan = readPlanRevision(workspace, orchestrationId, revision);
    if (plan !== undefined) plans.push(plan);
  }
  return plans;
}

