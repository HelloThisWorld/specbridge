export interface OrchestrationEvent extends Record<string, unknown> {
  at: string;
  type: OrchestrationEventType;
}

/**
 * Append one bounded event. Oversized payloads are refused rather than
 * truncated: a silently trimmed audit record is worse than a rejected one.
 */
export function appendOrchestrationEvent(
  workspace: WorkspaceInfo,
  orchestrationId: string,
  event: OrchestrationEvent,
  limits: { maxEventBytes: number },
): void {
  const line = `${JSON.stringify(event)}\n`;
  if (Buffer.byteLength(line, 'utf8') > limits.maxEventBytes) {
    throw new OrchestrationError(
      'SBO021',
      `Orchestration event of type "${event.type}" is larger than the configured ` +
        `${limits.maxEventBytes}-byte limit and was not recorded.`,
      { remediation: ['Record a shorter summary; full evidence lives in the run directory.'] },
    );
  }
  const file = artifactPath(workspace, orchestrationId, 'events.jsonl');
  mkdirSync(path.dirname(file), { recursive: true });
  appendFileSync(file, line, 'utf8');
}

export interface EventPage {
  events: OrchestrationEvent[];
  total: number;
  truncated: boolean;
}

/**
 * Read a bounded page of events, newest last.
 *
 * History is persisted in full but never returned in full by default: an
 * append-only log must not be able to produce an unbounded response.
 */
export function readOrchestrationEvents(
  workspace: WorkspaceInfo,
  orchestrationId: string,
  options: { limit?: number; offset?: number } = {},
): EventPage {
  const file = artifactPath(workspace, orchestrationId, 'events.jsonl');
  if (!existsSync(file)) return { events: [], total: 0, truncated: false };
  let raw: string;
  try {
    raw = readFileSync(file, 'utf8');
  } catch {
    return { events: [], total: 0, truncated: false };
  }
  const lines = raw.split('\n').filter((line) => line.trim().length > 0);
  const parsed: OrchestrationEvent[] = [];
  for (const line of lines) {
    try {
      const value: unknown = JSON.parse(line);
      if (value !== null && typeof value === 'object') parsed.push(value as OrchestrationEvent);
    } catch {
      // A partially written final line (crash during append) is skipped, not
      // fatal: the rest of the history stays readable.
    }
  }
  const limit = Math.max(1, Math.min(options.limit ?? 50, 500));
  const offset = Math.max(0, options.offset ?? 0);
  const window = parsed.slice(Math.max(0, parsed.length - offset - limit), parsed.length - offset);
  return { events: window, total: parsed.length, truncated: parsed.length > window.length };
}

export function countOrchestrationEvents(
  workspace: WorkspaceInfo,
  orchestrationId: string,
): number {
  const file = artifactPath(workspace, orchestrationId, 'events.jsonl');
  if (!existsSync(file)) return 0;
  try {
    // Counting newlines avoids materializing every parsed event.
    return readFileSync(file, 'utf8').split('\n').filter((line) => line.trim().length > 0).length;
  } catch {
    return 0;
  }
}

